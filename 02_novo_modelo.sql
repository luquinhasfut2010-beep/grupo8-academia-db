SET search_path TO academia, public;

DROP TABLE IF EXISTS checkin CASCADE;
DROP TABLE IF EXISTS pagamento CASCADE;
DROP TABLE IF EXISTS matricula CASCADE;
DROP TABLE IF EXISTS plano CASCADE;
DROP TABLE IF EXISTS aluno CASCADE;

CREATE TABLE aluno (
    aluno_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(120) NOT NULL,
    cpf      CHAR(11) NOT NULL UNIQUE,
    telefone VARCHAR(20)
);

CREATE TABLE plano (
    plano_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_plano   VARCHAR(60) NOT NULL UNIQUE,
    valor_mensal NUMERIC(10,2) NOT NULL CHECK (valor_mensal >= 0),
    ativo        BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE matricula (
    matricula_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id     BIGINT NOT NULL REFERENCES aluno(aluno_id),
    plano_id     BIGINT NOT NULL REFERENCES plano(plano_id),
    data_inicio  DATE NOT NULL,
    data_fim     DATE,
    status       VARCHAR(15) NOT NULL DEFAULT 'ATIVA',
    CONSTRAINT chk_matricula_status
        CHECK (status IN ('ATIVA', 'SUSPENSA', 'CANCELADA', 'ENCERRADA')),
    CONSTRAINT chk_matricula_periodo
        CHECK (data_fim IS NULL OR data_fim >= data_inicio),
    CONSTRAINT uq_matricula_aluno UNIQUE (aluno_id)
);

CREATE TABLE pagamento (
    pagamento_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL REFERENCES matricula(matricula_id),
    competencia  DATE NOT NULL,
    valor_cobrado NUMERIC(10,2) NOT NULL CHECK (valor_cobrado >= 0),
    data_vencimento DATE NOT NULL,
    data_pagamento DATE,
    status_pagamento VARCHAR(15) NOT NULL,
    CONSTRAINT chk_pagamento_status
        CHECK (status_pagamento IN ('PENDENTE', 'PAGO', 'ATRASADO', 'CANCELADO')),
    CONSTRAINT uq_pagamento_competencia UNIQUE (matricula_id, competencia)
);

-- A tabela de acesso contém apenas a matrícula e o momento da entrada.
CREATE TABLE checkin (
    checkin_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula_id BIGINT NOT NULL REFERENCES matricula(matricula_id),
    data_hora   TIMESTAMP NOT NULL
);

-- Índices para consultas recorrentes.
CREATE INDEX idx_matricula_aluno ON matricula(aluno_id);
CREATE INDEX idx_matricula_plano ON matricula(plano_id);
CREATE INDEX idx_pagamento_status_vencimento
    ON pagamento(status_pagamento, data_vencimento);
CREATE INDEX idx_checkin_data_hora ON checkin(data_hora);
CREATE INDEX idx_checkin_matricula_data
    ON checkin(matricula_id, data_hora);
