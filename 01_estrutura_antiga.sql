-- Estrutura antiga: dados cadastrais, plano e pagamento repetidos em cada acesso.
CREATE TABLE checkins (
    checkin_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_aluno       VARCHAR(120) NOT NULL,
    cpf              CHAR(11) NOT NULL,
    telefone         VARCHAR(20),
    nome_plano       VARCHAR(60) NOT NULL,
    valor_mensal     NUMERIC(10,2) NOT NULL CHECK (valor_mensal >= 0),
    status_pagamento VARCHAR(20) NOT NULL,
    competencia      DATE NOT NULL,
    data_vencimento  DATE NOT NULL,
    data_pagamento   DATE,
    data_hora        TIMESTAMP NOT NULL
);

